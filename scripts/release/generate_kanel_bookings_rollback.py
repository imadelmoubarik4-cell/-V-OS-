#!/usr/bin/env python3
"""Derive the S106–S109 rollback SQL and the pre-S106 expected-state fixture.

Inputs are two structural snapshots taken with scripts/release/kanel_bookings_snapshot.sql:
  A = a database migrated through S105 (what production runs today)
  B = the same database after S106, S107, S108 and S109

Outputs:
  docs/release/sql/KANEL_S106_S109_rollback.sql
      Idempotent, single-transaction rollback that returns every EXISTING object the
      release touched to its exact S105 definition, removes everything the release
      added that could act (functions, the trigger), and restores the S105 data values
      the release changed. Additive tables/columns are left in place (inert, data kept).
  scripts/release/kanel_pre_s106_expected.json
      The S105 state of every object the release touches. Used (a) to verify the
      rollback and (b) read-only against production BEFORE migrating, to prove
      production still matches the repo's S105 definitions (no drift).

  python3 scripts/release/generate_kanel_bookings_rollback.py A.json B.json
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
A, B = (json.loads(pathlib.Path(p).read_text()) for p in sys.argv[1:3])
fa, fb = A["functions"], B["functions"]
sig = lambda f: (f["src_md5"], f["secdef"], f["config"], f["acl"])

changed = sorted(k for k in set(fa) & set(fb) if sig(fa[k]) != sig(fb[k]))
added_fns = sorted(set(fb) - set(fa))
new_tables = set(B["tables"]) - set(A["tables"])
added_triggers = sorted(k for k in set(B["triggers"]) - set(A["triggers"]) if B["triggers"][k]["table"] not in new_tables)
changed_constraints = sorted(k for k in set(A["constraints"]) & set(B["constraints"]) if A["constraints"][k] != B["constraints"][k])
assert not (set(fa) - set(fb)), "the release removed a function; rollback must recreate it"
assert not (set(A["triggers"]) - set(B["triggers"])), "the release removed a trigger"
assert all(A["policies"].get(k) == B["policies"].get(k) for k in A["policies"]), "the release changed an existing RLS policy"
for k in changed:  # CREATE OR REPLACE keeps privileges, so the ACL must not have changed.
    assert fa[k]["acl"] == fb[k]["acl"], f"ACL changed on {k}; rollback would need GRANT/REVOKE"

def q(name):  # schema.table -> quoted
    s, t = name.split(".", 1)
    return f'{s}."{t}"' if not t.isidentifier() else name

out = []
w = out.append
w("-- KANEL × ALCEDO online bookings — ROLLBACK of S106, S107, S108 and S109.")
w("-- GENERATED by scripts/release/generate_kanel_bookings_rollback.py from replayed")
w("-- snapshots (S105 vs S109). Do not hand-edit; regenerate. Verified by")
w("-- scripts/release/verify_kanel_bookings_rollback.sh.")
w("--")
w("-- OWNER-APPROVED USE ONLY. Safe to run from any partial state (S106..S109): every")
w("-- statement is idempotent and the whole script is one transaction.")
w("--")
w("-- Restores to the exact S105 definitions: " + ", ".join(k.split("(")[0] for k in changed) + ".")
w("-- Removes: the lifecycle trigger and the " + str(len(added_fns)) + " functions S106–S109 added")
w("-- (the public guest-booking RPCs, the staff inbox RPCs and their helpers).")
w("-- Restores the S105 values of booking_settings.max_party_online / turnaround_minutes")
w("-- and the Bar's circular_adjacency (production confirmed 30 / 0 before release;")
w("-- if the pre-release backup recorded different values, use those instead).")
w("--")
w("-- Left in place on purpose (inert once the functions above are gone, data kept):")
w("--   tables  " + ", ".join(sorted(new_tables)))
cols = {t: sorted(set(B["tables"][t]) - set(A["tables"][t])) for t in A["tables"] if set(B["tables"].get(t, [])) - set(A["tables"][t])}
w("--   columns " + "; ".join(f"{t}({', '.join(c)})" for t, c in sorted(cols.items())))
w("-- Removing those is a separate, destructive decision (export first) — see the end.")
w("")
w("begin;")
w("")
w("-- 1. Stop the web-request workflow first (it fires only for public_token rows).")
for k in added_triggers:
    t = B["triggers"][k]
    w(f"drop trigger if exists {t['name']} on {q(t['table'])};")
w("")
w("-- 2. Web-push rows that only the release could create (inert: delivery is disabled).")
w("--    They must go before the S105 queue constraints can be restored.")
w("delete from atlas_private.push_notification_queue")
w(" where event_type = 'booking_request' or route = 'bookings';")
w("")
w("-- 3. Constraints the release widened -> exact S105 definitions.")
for k in changed_constraints:
    c = A["constraints"][k]
    w(f"alter table {q(c['table'])} drop constraint if exists {c['name']};")
    w(f"alter table {q(c['table'])} add constraint {c['name']} {c['def']};")
w("")
w("-- 4. Staff-facing functions the release rewrote -> exact S105 definitions")
w("--    (CREATE OR REPLACE keeps their existing grants).")
for k in changed:
    w(f"-- {k}")
    w(fa[k]["def"].rstrip() + ";")
    w("")
w("-- 5. Functions the release added (public guest RPCs, staff inbox RPCs, helpers).")
for k in added_fns:
    w(f"drop function if exists {k.split('(')[0]}({fb[k]['args']});")
w("")
w("-- 6. Data values the release changed -> S105 values.")
w("update atlas_private.booking_settings")
w("   set max_party_online = 30, turnaround_minutes = 0")
w(" where id = true;")
w("update atlas_private.booking_areas set circular_adjacency = true")
w(" where id = 'ba000000-0000-4000-8000-000000000001';")
w("")
w("-- 7. Ledger: S106–S109 no longer applied, so the reviewed apply bundles")
w("--    (docs/release/sql/KANEL_apply_*.sql) can re-apply them later.")
versions = sorted(f.name.split("_")[0] for f in (ROOT / "supabase/migrations").glob("*.sql") if f.name.split("_")[0] > "20261022090000")
w("delete from supabase_migrations.schema_migrations")
w(" where version in (" + ", ".join(f"'{v}'" for v in versions) + ");")
w("")
w("commit;")
w("")
w("-- OPTIONAL, DESTRUCTIVE, SEPARATE DECISION — run only after exporting the data:")
for t in sorted(new_tables):
    w(f"-- drop table if exists {t};")
for t, cs in sorted(cols.items()):
    w(f"-- alter table {t} " + ", ".join(f"drop column if exists {c}" for c in cs) + ";")

sql_path = ROOT / "docs/release/sql/KANEL_S106_S109_rollback.sql"
sql_path.parent.mkdir(parents=True, exist_ok=True)
sql_path.write_text("\n".join(out) + "\n", encoding="utf-8")

expected = {
    "note": "S105 state of every object S106-S109 touch. Generated; do not hand-edit.",
    "restored_functions": {k: {x: fa[k][x] for x in ("src_md5", "secdef", "config", "acl")} for k in changed},
    "release_functions": added_fns,
    "release_triggers": added_triggers,
    "restored_constraints": {k: A["constraints"][k]["def"] for k in changed_constraints},
}
exp_path = ROOT / "scripts/release/kanel_pre_s106_expected.json"
exp_path.write_text(json.dumps(expected, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"wrote {sql_path.relative_to(ROOT)} ({len(changed)} restored, {len(added_fns)} dropped, "
      f"{len(added_triggers)} trigger, {len(changed_constraints)} constraints)")
print(f"wrote {exp_path.relative_to(ROOT)}")
