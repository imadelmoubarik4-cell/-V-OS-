#!/usr/bin/env python3
"""Generate the reviewed production apply bundles for S106, S107, S108, S109, S110, S110b, S111 and S112.

Production runs on an adopted/squashed migration baseline, so `supabase db push` is
PROHIBITED (it would treat squashed history as pending). Each migration is applied
on its own, in order, through the Supabase SQL editor, using one bundle per file:

  docs/release/sql/KANEL_apply_<n>_<name>.sql
    begin;
    guard  — refuses unless the previous migration is recorded and this one is not;
    the migration file, byte for byte;
    the ledger row for this migration;
    commit;

So a bundle either applies its migration AND records it, or changes nothing. The
bundles are applied to a rolled-back replay in CI by
scripts/release/verify_kanel_bookings_rollback.sh, and
tests/python/test_kanel_release_tooling.py checks each embeds its file unchanged.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
S105 = "20261022090000"
BEGIN = "-- >>> migration file (verbatim) >>>"
END = "-- <<< end of migration file <<<"

files = sorted(p for p in (ROOT / "supabase/migrations").glob("*.sql") if p.name.split("_")[0] > S105)
assert [p.name.split("_")[0] for p in files] == ["20261023090000", "20261024090000", "20261025090000", "20261026090000", "20261027090000", "20261027120000", "20261028090000", "20261029090000"], files

prev = S105
out_dir = ROOT / "docs/release/sql"
for n, path in enumerate(files, 1):
    tag = f"{n}/4" if n <= 4 else f"{n} ({path.name.split('_')[1].upper()})"
    version = path.name.split("_")[0]
    name = path.stem.split("_", 1)[1]
    body = path.read_text(encoding="utf-8")
    bundle = f"""-- KANEL × ALCEDO online bookings — PRODUCTION APPLY {tag}: {path.name}
-- GENERATED by scripts/release/generate_kanel_apply_bundles.py. Do not hand-edit.
-- OWNER-APPROVED USE ONLY. Paste the WHOLE file into the Supabase SQL editor and run.
-- One transaction: the migration and its ledger row commit together or not at all.
-- Refuses (changes nothing) unless {prev} is recorded and {version} is not.
-- Never use `supabase db push` for this project (squashed ledger baseline).

begin;

do $guard$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '{prev}') then
    raise exception 'KANEL apply {tag} refused: previous migration {prev} is not recorded — apply the bundles in order';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations where version = '{version}') then
    raise exception 'KANEL apply {tag} refused: {version} is already recorded — nothing to do';
  end if;
end
$guard$;

{BEGIN}
{body.rstrip()}
{END}

insert into supabase_migrations.schema_migrations(version, name, statements)
values ('{version}', '{name}', array[]::text[]);

commit;
"""
    target = out_dir / f"KANEL_apply_{n}_{path.stem.split('_', 1)[1]}.sql"
    target.write_text(bundle, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    prev = version
