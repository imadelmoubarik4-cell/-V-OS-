#!/usr/bin/env python3
"""Generate the reviewed production apply bundle for S114 (staff access state).

Production runs on an adopted/squashed migration baseline, so `supabase db push` is
PROHIBITED. Like the KANEL bundles (generate_kanel_apply_bundles.py), the migration is
applied on its own through the Supabase SQL editor using one bundle:

  docs/release/sql/S114_apply_staff_access_state.sql
    begin;
    guard  — refuses unless S113 (20261030090000) is recorded and S114 is not;
    the migration file, byte for byte;
    the ledger row for this migration;
    commit;

tests/python/test_s114_staff_access_release.py checks the bundle embeds the file
unchanged; the rollback is docs/release/sql/S114_staff_access_state_rollback.sql.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
PREV = "20261030090000"
VERSION = "20261031090000"
BEGIN = "-- >>> migration file (verbatim) >>>"
END = "-- <<< end of migration file <<<"

path = ROOT / "supabase/migrations" / f"{VERSION}_s114_staff_access_state.sql"
name = path.stem.split("_", 1)[1]
body = path.read_text(encoding="utf-8")
bundle = f"""-- ALCEDO S114 staff access state — PRODUCTION APPLY: {path.name}
-- GENERATED by scripts/release/generate_s114_staff_access_bundle.py. Do not hand-edit.
-- OWNER-APPROVED USE ONLY. Paste the WHOLE file into the Supabase SQL editor and run.
-- One transaction: the migration and its ledger row commit together or not at all.
-- Refuses (changes nothing) unless {PREV} is recorded and {VERSION} is not.
-- Never use `supabase db push` for this project (squashed ledger baseline).

begin;

do $guard$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '{PREV}') then
    raise exception 'S114 apply refused: previous migration {PREV} is not recorded';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations where version = '{VERSION}') then
    raise exception 'S114 apply refused: {VERSION} is already recorded — nothing to do';
  end if;
end
$guard$;

{BEGIN}
{body.rstrip()}
{END}

insert into supabase_migrations.schema_migrations(version, name, statements)
values ('{VERSION}', '{name}', array[]::text[]);

commit;
"""
target = ROOT / "docs/release/sql/S114_apply_staff_access_state.sql"
target.write_text(bundle, encoding="utf-8")
print(f"wrote {target.relative_to(ROOT)}")
