#!/usr/bin/env python3
"""Derive the S113 rollback, the pre-S113 expected state and the S113 preflight.

Inputs are structural snapshots (scripts/release/kanel_bookings_snapshot.sql):
  A = a database at S112 (what production runs before S113)
  B = the same database after S113

Outputs:
  docs/release/sql/KANEL_S113_rollback.sql
      One idempotent transaction: stops the email schedule if it was installed,
      restores the exact S112 definition of the public request RPC, drops the
      settings trigger and the functions S113 added, removes test emails and puts
      the outbox kind rule back to S112, drops the guest_language rule, turns the
      owner switch off (every added column is kept unless its commented line is
      enabled) and removes the S113 ledger row (so the reviewed bundle can re-apply it).
  scripts/release/kanel_pre_s113_expected.json
      The S112 state of every object S113 touches (rollback check + drift check).
  docs/release/sql/KANEL_S113_preflight_readonly.sql
      One read-only SELECT for the Supabase SQL editor, run immediately before the
      S113 apply: ledger at S112, no S113 row, no drift in the touched function and
      the outbox kind rule, nothing of S113 present yet, plus informational rows
      (the emails the migration will discard, the extensions the schedule needs).

  python3 scripts/release/generate_kanel_s113_release.py A.json B.json
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
S112, S113 = "20261029090000", "20261030090000"
A, B = (json.loads(pathlib.Path(p).read_text(encoding="utf-8")) for p in sys.argv[1:3])
fa, fb = A["functions"], B["functions"]
sig = lambda f: (f["src_md5"], f["secdef"], f["config"], f["acl"])

changed = sorted(k for k in set(fa) & set(fb) if sig(fa[k]) != sig(fb[k]))
added = sorted(set(fb) - set(fa))
assert not (set(fa) - set(fb)), "S113 removed a function"
assert A["policies"] == B["policies"], "S113 must not change policies"
for k in changed:  # CREATE OR REPLACE keeps grants, so they must not have changed.
    assert fa[k]["acl"] == fb[k]["acl"], f"ACL changed on {k}"
assert changed == ["public.atlas_public_booking_request(p_payload jsonb)"], changed
assert added == [
    "atlas_private.booking_email_address_ok(p_email text)",
    "atlas_private.booking_email_queue_test()",
    "atlas_private.booking_email_render(p_outbox_id uuid)",
    "atlas_private.booking_email_tick()",
    "atlas_private.booking_settings_guest_email_since()",
    "public.atlas_booking_email_claim(p_limit integer)",
    "public.atlas_booking_email_complete(p_id uuid, p_outcome text, p_error text)",
    "public.atlas_booking_email_worker_secret()",
], added

TRIGGER = "atlas_private.booking_settings.booking_settings_guest_email_since"
added_triggers = sorted(set(B["triggers"]) - set(A["triggers"]))
assert added_triggers == [TRIGGER], added_triggers
assert all(A["triggers"][k] == B["triggers"][k] for k in A["triggers"]), "S113 changed an existing trigger"

KIND = "atlas_private.booking_email_outbox.booking_email_outbox_kind_check"
LANG = "atlas_private.reservations.reservations_guest_language_check"
con_changed = sorted(k for k in set(A["constraints"]) & set(B["constraints"]) if A["constraints"][k] != B["constraints"][k])
con_added = sorted(set(B["constraints"]) - set(A["constraints"]))
assert con_changed == [KIND], con_changed
assert con_added == [LANG], con_added
assert not (set(A["constraints"]) - set(B["constraints"])), "S113 removed a constraint"

table_changes = {k: v for k, v in B["tables"].items() if A["tables"].get(k) != v}
assert table_changes == {
    "atlas_private.reservations": A["tables"]["atlas_private.reservations"] + ["guest_language"],
    "atlas_private.booking_settings": A["tables"]["atlas_private.booking_settings"] + ["guest_email_enabled", "guest_email_since"],
    "atlas_private.booking_email_outbox": A["tables"]["atlas_private.booking_email_outbox"] + ["attempts", "next_attempt_at", "claimed_at"],
}, table_changes

lit = lambda s: "'" + str(s).replace("'", "''") + "'"
kind_def = A["constraints"][KIND]["def"]

# ---- rollback ---------------------------------------------------------------
out = []
w = out.append
w("-- KANEL × ALCEDO bookings — ROLLBACK of S113 (guest booking emails from kanel@kanel.is).")
w("-- GENERATED by scripts/release/generate_kanel_s113_release.py from replayed S112/S113")
w("-- snapshots. Do not hand-edit; regenerate. Verified by")
w("-- scripts/release/verify_kanel_bookings_rollback.sh (replay gate).")
w("--")
w("-- OWNER-APPROVED USE ONLY. One transaction, idempotent. Stops the email schedule")
w("-- (cron job kanel-booking-email) if it was installed; restores the exact S112 definition")
w("-- of " + ", ".join(k.split("(")[0] for k in changed) + "; drops the trigger")
w("-- booking_settings_guest_email_since and " + ", ".join(k.split("(")[0] for k in added) + ";")
w("-- removes test emails and puts the outbox kind rule back to S112; drops the guest_language")
w("-- rule; turns the owner switch off; clears the S113 ledger row. Guest emails already sent")
w("-- stay sent. The Edge Function atlas-booking-email-worker and its secrets are removed")
w("-- separately (runbook). Run this BEFORE KANEL_S112_rollback.sql (that script refuses")
w("-- while S113 is recorded).")
w("")
w("begin;")
w("")
w("do $guard$")
w("begin")
w("  if exists (select 1 from supabase_migrations.schema_migrations where version > " + lit(S113) + ") then")
w("    raise exception 'KANEL S113 rollback refused: a later migration is recorded — roll that back first';")
w("  end if;")
w("end")
w("$guard$;")
w("")
w("-- 1. The email schedule, if installed (pg_cron).")
w("do $cron$")
w("declare scheduled boolean;")
w("begin")
w("  -- Nested + dynamic so this also runs where pg_cron (and the cron schema) is absent.")
w("  if exists (select 1 from pg_catalog.pg_extension where extname = 'pg_cron') then")
w("    execute 'select exists (select 1 from cron.job where jobname = $1)' into scheduled using 'kanel-booking-email';")
w("    if scheduled then")
w("      execute 'select cron.unschedule($1)' using 'kanel-booking-email';")
w("    end if;")
w("  end if;")
w("end")
w("$cron$;")
w("")
w("-- 2. Functions S113 rewrote -> exact S112 definitions (grants are kept).")
for k in changed:
    w(f"-- {k}")
    w(fa[k]["def"].rstrip() + ";")
    w("")
w("-- 3. The trigger and the functions S113 added.")
w("drop trigger if exists booking_settings_guest_email_since on atlas_private.booking_settings;")
for k in added:
    w(f"drop function if exists {k.split('(')[0]}({fb[k]['args']});")
w("")
w("-- 4. Outbox kind rule back to S112 (test emails go first: S112 has no 'test' kind).")
w("delete from atlas_private.booking_email_outbox where kind = 'test';")
w("alter table atlas_private.booking_email_outbox drop constraint if exists booking_email_outbox_kind_check;")
w(f"alter table atlas_private.booking_email_outbox add constraint booking_email_outbox_kind_check {kind_def};")
w("alter table atlas_private.reservations drop constraint if exists reservations_guest_language_check;")
w("")
w("-- 5. Owner switch off. The added columns are kept (no data dropped); remove them only with owner approval:")
w("update atlas_private.booking_settings set guest_email_enabled = false where id = true;")
w("-- alter table atlas_private.booking_settings drop column if exists guest_email_enabled, drop column if exists guest_email_since;")
w("-- alter table atlas_private.reservations drop column if exists guest_language;")
w("-- alter table atlas_private.booking_email_outbox drop column if exists attempts, drop column if exists next_attempt_at, drop column if exists claimed_at;")
w("")
w("-- 6. Ledger: S113 no longer applied (the reviewed bundle can re-apply it).")
w(f"delete from supabase_migrations.schema_migrations where version = {lit(S113)};")
w("")
w("commit;")
(ROOT / "docs/release/sql/KANEL_S113_rollback.sql").write_text("\n".join(out) + "\n", encoding="utf-8")

# ---- expected pre-S113 state ---------------------------------------------------
expected = {
    "note": "S112 state of every object S113 touches. Generated; do not hand-edit.",
    "restored_functions": {k: {x: fa[k][x] for x in ("src_md5", "secdef", "config", "acl")} for k in changed},
    "release_functions": added,
    "release_triggers": added_triggers,
    "restored_constraints": {KIND: kind_def},
}
(ROOT / "scripts/release/kanel_pre_s113_expected.json").write_text(
    json.dumps(expected, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

# ---- preflight (read-only) -----------------------------------------------------
rows = []
for key, want in expected["restored_functions"].items():
    schema, name = key.split("(")[0].split(".")
    args = key[key.index("(") + 1:-1]
    base = (f"from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace "
            f"where n.nspname = {lit(schema)} and p.proname = {lit(name)} "
            f"and pg_catalog.pg_get_function_identity_arguments(p.oid) = {lit(args)}")
    rows.append(f"""select 'drift', {lit(name + ' body = S112')},
  case when (select pg_catalog.md5(p.prosrc) {base}) = {lit(want['src_md5'])} then 'PASS' else 'FAIL' end,
  coalesce((select 'md5 ' || pg_catalog.md5(p.prosrc) {base}), 'function missing')""")
    rows.append(f"""select 'drift', {lit(name + ' grants = S112')},
  case when (select coalesce(p.proacl::text, '') = {lit(want['acl'])} {base}) then 'PASS' else 'FAIL' end,
  coalesce((select coalesce(p.proacl::text, '') {base}), 'function missing')""")
added_names = ", ".join(lit(k.split("(")[0].split(".")[1]) for k in added)
sql = f"""-- KANEL × ALCEDO bookings — S113 PREFLIGHT (READ-ONLY). Run immediately before the
-- S113 apply bundle; keep the output. GENERATED by scripts/release/generate_kanel_s113_release.py.
-- Go only if there is no FAIL row. The 'impact' rows say what the apply will change.
select section, "check", status, detail from (
select 1 as ord, 'ledger' as section, 'production is at S112' as "check",
  case when (select max(version) from supabase_migrations.schema_migrations) = {lit(S112)} then 'PASS' else 'FAIL' end as status,
  'last migration ' || coalesce((select max(version) from supabase_migrations.schema_migrations), 'none') as detail
union all select 2, 'ledger', 'no S113 row yet',
  case when not exists (select 1 from supabase_migrations.schema_migrations where version = {lit(S113)}) then 'PASS' else 'FAIL' end, ''
union all select 3, * from ({' union all '.join('select * from (' + r + ') x' for r in rows)}) d
union all select 3, 'drift', 'outbox kind rule = S112',
  case when (select pg_catalog.pg_get_constraintdef(c.oid) from pg_catalog.pg_constraint c
              where c.conrelid = 'atlas_private.booking_email_outbox'::regclass and c.conname = 'booking_email_outbox_kind_check')
            = {lit(kind_def)} then 'PASS' else 'FAIL' end, ''
union all select 4, 'not yet released', 'email functions absent',
  case when not exists (select 1 from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('atlas_private', 'public') and p.proname in ({added_names})) then 'PASS' else 'FAIL' end, ''
union all select 4, 'not yet released', 'owner switch, language and retry columns absent',
  case when not exists (select 1 from pg_catalog.pg_attribute a where not a.attisdropped and (
      (a.attrelid = 'atlas_private.booking_settings'::regclass and a.attname in ('guest_email_enabled', 'guest_email_since'))
   or (a.attrelid = 'atlas_private.reservations'::regclass and a.attname = 'guest_language')
   or (a.attrelid = 'atlas_private.booking_email_outbox'::regclass and a.attname in ('attempts', 'next_attempt_at', 'claimed_at'))))
    then 'PASS' else 'FAIL' end, ''
union all select 5, 'settings', 'sender address (booking_email_from)', 'INFO',
  (select coalesce(booking_email_from, 'none') from atlas_private.booking_settings where id = true)
union all select 6, 'impact', 'queued guest emails the apply discards (owner decision; never sent)', 'INFO',
  (select pg_catalog.count(*)::text from atlas_private.booking_email_outbox where status = 'queued')
union all select 7, 'schedule', 'pg_net available (needed later by the owner-run schedule install)', 'INFO',
  case when exists (select 1 from pg_catalog.pg_extension where extname = 'pg_net') then 'installed'
       when exists (select 1 from pg_catalog.pg_available_extensions where name = 'pg_net') then 'available, not installed'
       else 'not available' end
union all select 7, 'schedule', 'pg_cron installed', 'INFO',
  case when exists (select 1 from pg_catalog.pg_extension where extname = 'pg_cron') then 'installed' else 'not installed' end
) checks order by ord, "check";
"""
(ROOT / "docs/release/sql/KANEL_S113_preflight_readonly.sql").write_text(sql, encoding="utf-8")
print(f"wrote KANEL_S113_rollback.sql ({len(changed)} restored, {len(added)} dropped), "
      "kanel_pre_s113_expected.json, KANEL_S113_preflight_readonly.sql")
