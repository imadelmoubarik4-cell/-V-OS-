#!/usr/bin/env python3
"""Generate docs/release/sql/KANEL_preflight_readonly.sql from kanel_pre_s106_expected.json.

The preflight is ONE read-only SELECT (catalog + table reads only, no writes) for the
Supabase SQL editor. It returns one row per check: section, check, status
(PASS / WARN / FAIL / INFO) and detail. Run it immediately before the release and
save the output with the release record.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
exp = json.loads((ROOT / "scripts/release/kanel_pre_s106_expected.json").read_text())
lit = lambda s: "'" + str(s).replace("'", "''") + "'"
BAR = "'ba000000-0000-4000-8000-000000000001'"

rows = []
for key, want in exp["restored_functions"].items():
    schema_name = key.split("(")[0]
    schema, name = schema_name.split(".")
    args = key[key.index("(") + 1:-1]
    base = (f"from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace "
            f"where n.nspname = {lit(schema)} and p.proname = {lit(name)} "
            f"and pg_catalog.pg_get_function_identity_arguments(p.oid) = {lit(args)}")
    rows.append(f"""select 'drift' as section, {lit(name + ' body = S105')} as check,
  case when (select pg_catalog.md5(p.prosrc) {base}) = {lit(want['src_md5'])} then 'PASS' else 'FAIL' end as status,
  coalesce((select 'md5 ' || pg_catalog.md5(p.prosrc) {base}), 'function missing') as detail""")
    rows.append(f"""select 'drift', {lit(name + ' security + search_path = S105')},
  case when (select p.prosecdef = {str(want['secdef']).lower()} and coalesce(pg_catalog.array_to_string(p.proconfig, ','), '') = {lit(want['config'])} {base}) then 'PASS' else 'FAIL' end,
  coalesce((select 'secdef ' || p.prosecdef || ', ' || coalesce(pg_catalog.array_to_string(p.proconfig, ','), '') {base}), 'function missing')""")
    rows.append(f"""select 'drift', {lit(name + ' grants = S105')},
  case when (select coalesce(p.proacl::text, '') = {lit(want['acl'])} {base}) then 'PASS' else 'WARN' end,
  coalesce((select coalesce(p.proacl::text, '') {base}), 'function missing')""")
for key, want in exp["restored_constraints"].items():
    schema, table, con = key.split(".")
    rows.append(f"""select 'drift', {lit(con + ' = S105')},
  case when (select pg_catalog.pg_get_constraintdef(c.oid) from pg_catalog.pg_constraint c join pg_catalog.pg_class t on t.oid = c.conrelid
             join pg_catalog.pg_namespace n on n.oid = t.relnamespace where n.nspname = {lit(schema)} and t.relname = {lit(table)} and c.conname = {lit(con)}) = {lit(want)}
       then 'PASS' else 'FAIL' end, {lit(want)}""")
names = sorted({k.split("(")[0] for k in exp["release_functions"]})
rows.append(f"""select 'not yet released', 'no S106–S109 function exists yet',
  case when count(*) = 0 then 'PASS' else 'FAIL' end, coalesce(string_agg(n.nspname || '.' || p.proname, ', '), 'none')
  from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace
  where n.nspname || '.' || p.proname in ({', '.join(lit(x) for x in names)})""")
rows.append("""select 'not yet released', 'booking lifecycle trigger absent',
  case when count(*) = 0 then 'PASS' else 'FAIL' end, count(*)::text
  from pg_catalog.pg_trigger where tgname = 'booking_lifecycle_notify_trg'""")

sql = f"""-- KANEL × ALCEDO online bookings — PRODUCTION PREFLIGHT (READ-ONLY).
-- GENERATED by scripts/release/generate_kanel_preflight.py. Do not hand-edit.
-- One SELECT; reads catalogs and booking tables only; writes nothing.
-- Run in the Supabase SQL editor immediately before the release and keep the output.
-- Go only if there is no FAIL row; every WARN row needs an explicit owner decision.
with ledger as (
  select max(version) as last_version, count(*) filter (where version >= '20261023000000') as release_rows
  from supabase_migrations.schema_migrations
), settings as (
  select max_party_online, turnaround_minutes, slot_interval_minutes, default_duration_minutes, advance_days, auto_confirm
  from atlas_private.booking_settings where id = true
), bar as (
  select * from atlas_private.booking_areas where id = {BAR}
), stools as (
  select id, label, position_index from atlas_private.booking_tables where area_id = {BAR}
), live as (  -- active future allocations
  select rt.table_id, rt.reservation_id, rt.start_at, rt.end_at, r.party_size, r.source, r.booking_reference
  from atlas_private.reservation_tables rt join atlas_private.reservations r on r.id = rt.reservation_id
  where rt.released_at is null and rt.end_at > pg_catalog.now()
    and r.status in ('requested','confirmed','arrived','seated')
), tight as (  -- same stool, next booking starts less than 15 minutes after the previous ends
  select a.booking_reference as first_ref, b.booking_reference as next_ref, t.label,
         (extract(epoch from (b.start_at - a.end_at)) / 60)::int as gap_min, b.start_at
  from live a join live b on a.table_id = b.table_id and a.reservation_id <> b.reservation_id
   and b.start_at >= a.end_at and b.start_at < a.end_at + interval '15 minutes'
  join atlas_private.booking_tables t on t.id = a.table_id
), groups as (  -- future multi-stool Bar allocations
  select l.reservation_id, min(l.booking_reference) as ref, count(*) as stools,
         min(s.position_index) as lo, max(s.position_index) as hi,
         count(distinct case when s.position_index between 1 and 8 then 'A'
                             when s.position_index between 9 and 12 then 'B'
                             when s.position_index between 13 and 16 then 'C' end) as sections
  from live l join stools s on s.id = l.table_id group by l.reservation_id having count(*) > 1
), hours as (
  select weekday, is_open, open_time, close_time, close_next_day,
    (extract(hour from close_time) * 60 + extract(minute from close_time))::int
      + case when close_next_day then 1440 else 0 end - 120 as last_start_min,
    (extract(hour from open_time) * 60 + extract(minute from open_time))::int as open_min
  from atlas_private.settings_business_hours
)
select section, "check", status, detail from (
select 1 as ord, 'ledger' as section, 'production is at S105' as check,
  case when (select last_version from ledger) = '20261022090000' then 'PASS' else 'FAIL' end as status,
  'last migration ' || coalesce((select last_version from ledger), 'none') as detail
union all select 2, 'ledger', 'no S106–S109 rows in the migration ledger',
  case when (select release_rows from ledger) = 0 then 'PASS' else 'FAIL' end, (select release_rows from ledger)::text
union all select 3, *  from ({' union all '.join('select * from (' + r + ') x' for r in rows)}) d
union all select 10, 'settings', 'current online cap / turnaround (S106 sets 4 / 15)',
  case when (select max_party_online = 30 and turnaround_minutes = 0 from settings) then 'INFO' else 'WARN' end,
  (select 'max_party_online ' || max_party_online || ', turnaround_minutes ' || turnaround_minutes
     || ' (rollback restores 30 / 0 — if these differ, edit the rollback values)' from settings)
union all select 11, 'settings', 'other booking settings (unchanged by the release)', 'INFO',
  (select 'slot ' || slot_interval_minutes || ' min, duration ' || default_duration_minutes || ' min, advance '
     || advance_days || ' days, auto_confirm ' || auto_confirm from settings)
union all select 20, 'bar', 'Bar area exists with the seeded id',
  case when exists (select 1 from bar where is_active) then 'PASS' else 'FAIL' end,
  coalesce((select name || ', active ' || is_active || ', circular_adjacency ' || circular_adjacency from bar), 'missing — S106 sections and online availability would not apply')
union all select 21, 'bar', 'Bar has 16 stools at positions 1–16 (sections A 1–8, B 9–12, C 13–16)',
  case when (select count(*) = 16 and count(distinct position_index) = 16 and min(position_index) = 1 and max(position_index) = 16 from stools) then 'PASS' else 'FAIL' end,
  (select count(*) || ' stools; positions ' || coalesce(min(position_index)::text, '-') || '–' || coalesce(max(position_index)::text, '-') from stools)
union all select 22, 'bar', 'stool labels match their positions (Bar n at position n)',
  case when not exists (select 1 from stools where label <> 'Bar ' || position_index) then 'PASS' else 'WARN' end,
  coalesce((select string_agg(label || '@' || coalesce(position_index::text, 'null'), ', ') from stools where label <> 'Bar ' || coalesce(position_index::text, '')), 'all match')
union all select 23, 'areas', 'areas (only the Bar becomes online-bookable)', 'INFO',
  (select string_agg(name || case when is_active then '' else ' (inactive)' end, ', ' order by display_order) from atlas_private.booking_areas)
union all select 30 + weekday, 'hours',
  'weekday ' || weekday || ' (0 = Sunday) — owner to confirm',
  case when not is_open then 'INFO' when open_time is null or close_time is null then 'WARN' else 'INFO' end,
  case when not is_open then 'closed'
       when open_time is null or close_time is null then 'open but times missing — no online times that day'
       else to_char(open_time, 'HH24:MI') || '–' || to_char(close_time, 'HH24:MI') || case when close_next_day then ' (+1 day)' else '' end
         || '; latest online start ' || lpad(((open_min + ((last_start_min - open_min) / 15) * 15) / 60 % 24)::text, 2, '0') || ':'
         || lpad(((open_min + ((last_start_min - open_min) / 15) * 15) % 60)::text, 2, '0') end
  from hours
union all select 40, 'impact', 'future back-to-back bookings closer than the new 15-min turnaround',
  case when (select count(*) from tight) = 0 then 'PASS' else 'WARN' end,
  coalesce((select count(*) || ': ' || string_agg(label || ' ' || first_ref || '→' || next_ref || ' (' || gap_min || ' min, ' || to_char(start_at at time zone 'Atlantic/Reykjavik', 'DD Mon HH24:MI') || ')', '; ') from (select * from tight order by start_at limit 20) t), 'none')
union all select 41, 'impact', 'future multi-stool Bar bookings that cross sections or are not contiguous',
  case when not exists (select 1 from groups where sections > 1 or hi - lo + 1 <> stools) then 'PASS' else 'WARN' end,
  coalesce((select string_agg(ref || ' (stools ' || lo || '–' || hi || ')', '; ') from groups where sections > 1 or hi - lo + 1 <> stools), 'none')
union all select 42, 'impact', 'future website bookings above the new online cap of 4', 'INFO',
  (select count(*)::text from atlas_private.reservations where source = 'web' and party_size > 4 and start_at > pg_catalog.now()
     and status in ('requested','confirmed'))
union all select 43, 'impact', 'future active bookings (all sources)', 'INFO',
  (select count(*)::text from atlas_private.reservations where start_at > pg_catalog.now() and status in ('requested','confirmed','arrived','seated'))
union all select 50, 'queue', 'web-push queue rows (delivery disabled)', 'INFO',
  (select coalesce(string_agg(event_type || ' ' || n, ', '), 'empty') from (select event_type, count(*) as n from atlas_private.push_notification_queue group by event_type) q)
) checks order by ord, "check";
"""
path = ROOT / "docs/release/sql/KANEL_preflight_readonly.sql"
path.write_text(sql, encoding="utf-8")
print(f"wrote {path.relative_to(ROOT)}")
