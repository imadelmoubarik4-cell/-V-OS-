#!/usr/bin/env python3
"""Derive the S112 rollback, the pre-S112 expected state and the S112 preflight.

Inputs are structural snapshots (scripts/release/kanel_bookings_snapshot.sql):
  A = a database at S111 (what production runs before S112)
  B = the same database after S112

Outputs:
  docs/release/sql/KANEL_S112_rollback.sql
      One idempotent transaction: every function S112 rewrote goes back to its
      exact S111 definition, the four public-seat helpers S112 added are dropped,
      the Bar stools get their pre-S112 numbers, labels and sections back (same ids
      and floor positions, so allocations are untouched), the owner switch is turned
      off (its column stays unless the commented line is enabled) and the S112 ledger
      row is removed (so the reviewed bundle can re-apply it).
  scripts/release/kanel_pre_s112_expected.json
      The S111 state of every function S112 touches (rollback check + drift check).
  docs/release/sql/KANEL_S112_preflight_readonly.sql
      One read-only SELECT for the Supabase SQL editor, run immediately before the
      S112 apply: ledger at S111, no S112 row, no drift in the touched functions,
      helpers and switch absent, the 16 Bar stools still in their pre-S112 numbering,
      no label clash, plus informational impact rows.

  python3 scripts/release/generate_kanel_s112_release.py A.json B.json
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
S111, S112 = "20261028090000", "20261029090000"
A, B = (json.loads(pathlib.Path(p).read_text(encoding="utf-8")) for p in sys.argv[1:3])
fa, fb = A["functions"], B["functions"]
sig = lambda f: (f["src_md5"], f["secdef"], f["config"], f["acl"])

changed = sorted(k for k in set(fa) & set(fb) if sig(fa[k]) != sig(fb[k]))
added = sorted(set(fb) - set(fa))
assert not (set(fa) - set(fb)), "S112 removed a function"
assert A["triggers"] == B["triggers"], "S112 must not change triggers"
assert A["constraints"] == B["constraints"], "S112 must not change constraints"
assert A["policies"] == B["policies"], "S112 must not change policies"
table_changes = {k: v for k, v in B["tables"].items() if A["tables"].get(k) != v}
assert table_changes == {"atlas_private.booking_settings": A["tables"]["atlas_private.booking_settings"] + ["public_instant_confirm"]}, table_changes
for k in changed:  # CREATE OR REPLACE keeps grants, so they must not have changed.
    assert fa[k]["acl"] == fb[k]["acl"], f"ACL changed on {k}"
assert set(changed) == {
    "atlas_private.booking_lifecycle_notify()",
    "public.atlas_public_booking_availability(p_date date, p_party_size integer, p_tz text)",
    "public.atlas_public_booking_request(p_payload jsonb)",
}, changed
assert added == [
    "atlas_private.booking_public_free_seats(p_area_id uuid, p_start timestamp with time zone, p_end timestamp with time zone)",
    "atlas_private.booking_public_has_run(p_area_id uuid, p_free integer[], p_party integer)",
    "atlas_private.booking_public_reservation_seats(p_reservation_id uuid)",
    "atlas_private.booking_public_seat_ids(p_area_id uuid, p_seats integer[])",
], added

lit = lambda s: "'" + str(s).replace("'", "''") + "'"
BAR = "ba000000-0000-4000-8000-000000000001"
# Pre-S112 (S103/S106) numbering: seed id bb…NN carried number NN; sections A 1-8, B 9-12, C 13-16.
OLD_SECTION = "case when n <= 8 then 'A' when n <= 12 then 'B' else 'C' end"
SEEDS = ", ".join(f"('bb000000-0000-4000-8000-0000000000{n:02d}'::uuid, {n})" for n in range(1, 17))

# ---- rollback ---------------------------------------------------------------
out = []
w = out.append
w("-- KANEL × ALCEDO bookings — ROLLBACK of S112 (direct website booking, guest-chosen stools).")
w("-- GENERATED by scripts/release/generate_kanel_s112_release.py from replayed S111/S112")
w("-- snapshots. Do not hand-edit; regenerate. Verified by")
w("-- scripts/release/verify_kanel_bookings_rollback.sh (replay gate).")
w("--")
w("-- OWNER-APPROVED USE ONLY. One transaction, idempotent. Restores the exact S111")
w("-- definitions of: " + ", ".join(k.split("(")[0] for k in changed) + ";")
w("-- drops " + ", ".join(k.split("(")[0] for k in added) + ";")
w("-- gives the 16 Bar stools their pre-S112 numbers, labels and sections back (same ids and floor")
w("-- positions, so every allocation and hold stays on the same physical stool); turns the owner")
w("-- switch off; clears the S112 ledger row. Bookings confirmed directly stay confirmed.")
w("-- Run this BEFORE KANEL_S111_rollback.sql (that script refuses while S112 is recorded).")
w("")
w("begin;")
w("")
w("do $guard$")
w("begin")
w("  if exists (select 1 from supabase_migrations.schema_migrations where version > " + lit(S112) + ") then")
w("    raise exception 'KANEL S112 rollback refused: a later migration is recorded — roll that back first';")
w("  end if;")
w("end")
w("$guard$;")
w("")
w("-- 1. Functions S112 rewrote -> exact S111 definitions (grants are kept).")
for k in changed:
    w(f"-- {k}")
    w(fa[k]["def"].rstrip() + ";")
    w("")
w("-- 2. The functions S112 added.")
for k in added:
    w(f"drop function if exists {k.split('(')[0]}({fb[k]['args']});")
w("")
w("-- 3. Bar stools: pre-S112 numbers, labels and sections (two steps: label and position are unique).")
w(f"with seed(id, n) as (values {SEEDS})")
w("update atlas_private.booking_tables t")
w("set position_index = 100 + s.n, label = 'Bar ' || s.n || ' (renumbering)'")
w("from seed s")
w(f"where t.id = s.id and t.area_id = {lit(BAR)}")
w("  and (t.position_index is distinct from s.n or t.label is distinct from 'Bar ' || s.n);")
w("update atlas_private.booking_tables t")
w("set position_index = t.position_index - 100, label = 'Bar ' || (t.position_index - 100), updated_at = pg_catalog.now()")
w(f"where t.area_id = {lit(BAR)} and t.position_index between 101 and 116;")
w("update atlas_private.booking_tables t")
w("set segment = " + OLD_SECTION.replace("n <=", "t.position_index <="))
w(f"where t.area_id = {lit(BAR)} and t.position_index between 1 and 16;")
w("comment on column atlas_private.booking_tables.segment is")
w("  'Physical seating section within an area. Adjacency never crosses sections. '")
w("  'NULL = the area is not segmented. Bar: A = stools 1-8, B = 9-12, C = 13-16.';")
w("")
w("-- 4. Owner switch off. The column is kept (no data dropped); remove it only with owner approval:")
w("update atlas_private.booking_settings set public_instant_confirm = false where id = true;")
w("-- alter table atlas_private.booking_settings drop column if exists public_instant_confirm;")
w("")
w("-- 5. Ledger: S112 no longer applied (the reviewed bundle can re-apply it).")
w(f"delete from supabase_migrations.schema_migrations where version = {lit(S112)};")
w("")
w("commit;")
(ROOT / "docs/release/sql/KANEL_S112_rollback.sql").write_text("\n".join(out) + "\n", encoding="utf-8")

# ---- expected pre-S112 state ---------------------------------------------------
expected = {
    "note": "S111 state of every function S112 touches. Generated; do not hand-edit.",
    "restored_functions": {k: {x: fa[k][x] for x in ("src_md5", "secdef", "config", "acl")} for k in changed},
    "release_functions": added,
    "release_triggers": [],
    "restored_constraints": {},
}
(ROOT / "scripts/release/kanel_pre_s112_expected.json").write_text(
    json.dumps(expected, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

# ---- preflight (read-only) -----------------------------------------------------
rows = []
for key, want in expected["restored_functions"].items():
    schema, name = key.split("(")[0].split(".")
    args = key[key.index("(") + 1:-1]
    base = (f"from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace "
            f"where n.nspname = {lit(schema)} and p.proname = {lit(name)} "
            f"and pg_catalog.pg_get_function_identity_arguments(p.oid) = {lit(args)}")
    rows.append(f"""select 'drift', {lit(name + ' body = S111')},
  case when (select pg_catalog.md5(p.prosrc) {base}) = {lit(want['src_md5'])} then 'PASS' else 'FAIL' end,
  coalesce((select 'md5 ' || pg_catalog.md5(p.prosrc) {base}), 'function missing')""")
    rows.append(f"""select 'drift', {lit(name + ' grants = S111')},
  case when (select coalesce(p.proacl::text, '') = {lit(want['acl'])} {base}) then 'PASS' else 'FAIL' end,
  coalesce((select coalesce(p.proacl::text, '') {base}), 'function missing')""")
helper_names = ", ".join(lit(k.split("(")[0].split(".")[1]) for k in added)
sql = f"""-- KANEL × ALCEDO bookings — S112 PREFLIGHT (READ-ONLY). Run immediately before the
-- S112 apply bundle; keep the output. GENERATED by scripts/release/generate_kanel_s112_release.py.
-- Go only if there is no FAIL row. The 'impact' rows say what staff will notice.
with seed(id, n) as (values {SEEDS})
select section, "check", status, detail from (
select 1 as ord, 'ledger' as section, 'production is at S111' as "check",
  case when (select max(version) from supabase_migrations.schema_migrations) = {lit(S111)} then 'PASS' else 'FAIL' end as status,
  'last migration ' || coalesce((select max(version) from supabase_migrations.schema_migrations), 'none') as detail
union all select 2, 'ledger', 'no S112 row yet',
  case when not exists (select 1 from supabase_migrations.schema_migrations where version = {lit(S112)}) then 'PASS' else 'FAIL' end, ''
union all select 3, * from ({' union all '.join('select * from (' + r + ') x' for r in rows)}) d
union all select 4, 'not yet released', 'public seat helpers absent',
  case when not exists (select 1 from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'atlas_private' and p.proname in ({helper_names})) then 'PASS' else 'FAIL' end, ''
union all select 4, 'not yet released', 'owner switch public_instant_confirm absent',
  case when not exists (select 1 from pg_catalog.pg_attribute a where a.attrelid = 'atlas_private.booking_settings'::regclass
    and a.attname = 'public_instant_confirm' and not a.attisdropped) then 'PASS' else 'FAIL' end, ''
union all select 5, 'stools', 'the 16 Bar stools are in their pre-S112 numbering (Bar N = seed N, sections A/B/C)',
  case when (select pg_catalog.count(*) from seed s join atlas_private.booking_tables t on t.id = s.id
              where t.area_id = {lit(BAR)} and t.position_index = s.n and t.label = 'Bar ' || s.n
                and t.segment = {OLD_SECTION.replace('n <=', 's.n <=')}) = 16 then 'PASS' else 'FAIL' end,
  (select pg_catalog.count(*)::text || ' of 16 match' from seed s join atlas_private.booking_tables t on t.id = s.id
    where t.area_id = {lit(BAR)} and t.position_index = s.n and t.label = 'Bar ' || s.n)
union all select 5, 'stools', 'no other table uses a Bar 1-16 label or position (renumbering needs them free)',
  case when not exists (select 1 from atlas_private.booking_tables t where t.id not in (select id from seed)
      and (t.label ~ '^Bar ([1-9]|1[0-6])( |$)' or (t.area_id = {lit(BAR)} and t.position_index between 1 and 116)))
    then 'PASS' else 'FAIL' end,
  coalesce((select string_agg(t.label, ', ') from atlas_private.booking_tables t where t.id not in (select id from seed)
      and (t.label ~ '^Bar ([1-9]|1[0-6])( |$)' or (t.area_id = {lit(BAR)} and t.position_index between 1 and 116))), 'none')
union all select 6, 'settings', 'online booking switches (S112 adds public_instant_confirm, OFF)', 'INFO',
  (select 'public_online_enabled ' || public_online_enabled || ', auto_confirm ' || auto_confirm
     || ', max_party_online ' || max_party_online from atlas_private.booking_settings where id = true)
union all select 7, 'impact', 'future bookings sitting on Bar stools (their stool numbers change, same physical stools)', 'INFO',
  (select pg_catalog.count(distinct r.id)::text from atlas_private.reservations r
     join atlas_private.reservation_tables rt on rt.reservation_id = r.id and rt.released_at is null
     join seed s on s.id = rt.table_id
    where r.end_at > pg_catalog.now() and r.status in ('confirmed','arrived','seated'))
union all select 8, 'impact', 'future active bookings (all sources)', 'INFO',
  (select pg_catalog.count(*)::text from atlas_private.reservations where start_at > pg_catalog.now()
     and status in ('requested','confirmed','arrived','seated'))
) checks order by ord, "check";
"""
(ROOT / "docs/release/sql/KANEL_S112_preflight_readonly.sql").write_text(sql, encoding="utf-8")
print(f"wrote KANEL_S112_rollback.sql ({len(changed)} restored, {len(added)} dropped), "
      "kanel_pre_s112_expected.json, KANEL_S112_preflight_readonly.sql")
