#!/usr/bin/env python3
"""Derive the S110 rollback, the pre-S110 expected state and the S110 preflight.

Inputs are structural snapshots (scripts/release/kanel_bookings_snapshot.sql):
  A = a database at S109 (what production runs after A3)
  B = the same database after S110

Outputs:
  docs/release/sql/KANEL_S110_rollback.sql
      One idempotent transaction: every function S110 rewrote goes back to its
      exact S109 definition, the function S110 added is dropped, and the S110
      ledger row is removed (so the reviewed bundle can re-apply it).
  scripts/release/kanel_pre_s110_expected.json
      The S109 state of every function S110 touches (rollback check + drift check).
  docs/release/sql/KANEL_S110_preflight_readonly.sql
      One read-only SELECT for the Supabase SQL editor, run immediately before the
      S110 apply: ledger at S109, no S110 row, no drift in the touched functions,
      helper absent, plus the live allocations the stricter rule would now refuse
      to re-assign unchanged (informational).

  python3 scripts/release/generate_kanel_s110_release.py A.json B.json
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
S109, S110 = "20261026090000", "20261027090000"
A, B = (json.loads(pathlib.Path(p).read_text()) for p in sys.argv[1:3])
fa, fb = A["functions"], B["functions"]
sig = lambda f: (f["src_md5"], f["secdef"], f["config"], f["acl"])

changed = sorted(k for k in set(fa) & set(fb) if sig(fa[k]) != sig(fb[k]))
added = sorted(set(fb) - set(fa))
assert not (set(fa) - set(fb)), "S110 removed a function"
assert A["triggers"] == B["triggers"], "S110 must not change triggers"
assert A["constraints"] == B["constraints"], "S110 must not change constraints"
assert A["policies"] == B["policies"], "S110 must not change policies"
assert A["tables"] == B["tables"], "S110 must not change tables or columns"
for k in changed:  # CREATE OR REPLACE keeps grants, so they must not have changed.
    assert fa[k]["acl"] == fb[k]["acl"], f"ACL changed on {k}"
assert set(changed) == {
    "atlas_private.booking_table_json(p_table_id uuid)",
    "public.atlas_bookings_assign(p_actor_id uuid, p_actor_role text, p_reservation_id uuid, p_table_ids jsonb)",
    "public.atlas_bookings_create(p_actor_id uuid, p_actor_role text, p_payload jsonb)",
}, changed
assert added == ["atlas_private.booking_check_seat_group(p_table_ids uuid[], p_area_id uuid, p_party integer, p_start timestamp with time zone, p_end timestamp with time zone, p_ignore_reservation uuid)"], added

lit = lambda s: "'" + str(s).replace("'", "''") + "'"

# ---- rollback ---------------------------------------------------------------
out = []
w = out.append
w("-- KANEL × ALCEDO bookings — ROLLBACK of S110 (booking seat integrity).")
w("-- GENERATED by scripts/release/generate_kanel_s110_release.py from replayed S109/S110")
w("-- snapshots. Do not hand-edit; regenerate. Verified by")
w("-- scripts/release/verify_kanel_bookings_rollback.sh (replay gate).")
w("--")
w("-- OWNER-APPROVED USE ONLY. One transaction, idempotent. Restores the exact S109")
w("-- definitions of: " + ", ".join(k.split("(")[0] for k in changed) + ";")
w("-- drops " + ", ".join(k.split("(")[0] for k in added) + "; clears the S110 ledger row.")
w("-- No data is changed: seat allocations made under S110 are valid under S109 too.")
w("-- Run this BEFORE KANEL_S106_S109_rollback.sql (that script refuses while S110 is recorded).")
w("")
w("begin;")
w("")
w("-- 1. Functions S110 rewrote -> exact S109 definitions (grants are kept).")
for k in changed:
    w(f"-- {k}")
    w(fa[k]["def"].rstrip() + ";")
    w("")
w("-- 2. The function S110 added.")
for k in added:
    w(f"drop function if exists {k.split('(')[0]}({fb[k]['args']});")
w("")
w("-- 3. Ledger: S110 no longer applied (the reviewed bundle can re-apply it).")
w(f"delete from supabase_migrations.schema_migrations where version = '{S110}';")
w("")
w("commit;")
(ROOT / "docs/release/sql/KANEL_S110_rollback.sql").write_text("\n".join(out) + "\n", encoding="utf-8")

# ---- expected pre-S110 state ---------------------------------------------------
expected = {
    "note": "S109 state of every function S110 touches. Generated; do not hand-edit.",
    "restored_functions": {k: {x: fa[k][x] for x in ("src_md5", "secdef", "config", "acl")} for k in changed},
    "release_functions": added,
    "release_triggers": [],
    "restored_constraints": {},
}
(ROOT / "scripts/release/kanel_pre_s110_expected.json").write_text(
    json.dumps(expected, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

# ---- preflight (read-only) -----------------------------------------------------
rows = []
for key, want in expected["restored_functions"].items():
    schema, name = key.split("(")[0].split(".")
    args = key[key.index("(") + 1:-1]
    base = (f"from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace "
            f"where n.nspname = {lit(schema)} and p.proname = {lit(name)} "
            f"and pg_catalog.pg_get_function_identity_arguments(p.oid) = {lit(args)}")
    rows.append(f"""select 'drift', {lit(name + ' body = S109')},
  case when (select pg_catalog.md5(p.prosrc) {base}) = {lit(want['src_md5'])} then 'PASS' else 'FAIL' end,
  coalesce((select 'md5 ' || pg_catalog.md5(p.prosrc) {base}), 'function missing')""")
    rows.append(f"""select 'drift', {lit(name + ' grants = S109')},
  case when (select coalesce(p.proacl::text, '') = {lit(want['acl'])} {base}) then 'PASS' else 'FAIL' end,
  coalesce((select coalesce(p.proacl::text, '') {base}), 'function missing')""")
sql = f"""-- KANEL × ALCEDO bookings — S110 PREFLIGHT (READ-ONLY). Run immediately before the
-- S110 apply bundle; keep the output. GENERATED by scripts/release/generate_kanel_s110_release.py.
-- Go only if there is no FAIL row; every WARN row needs an explicit owner decision.
with live as (
  select r.id, r.booking_reference, r.party_size, r.start_at,
         pg_catalog.array_agg(rt.table_id) as seats,
         pg_catalog.sum(t.seat_capacity)::int as capacity
  from atlas_private.reservations r
  join atlas_private.reservation_tables rt on rt.reservation_id = r.id and rt.released_at is null
  join atlas_private.booking_tables t on t.id = rt.table_id
  where r.status in ('confirmed','arrived','seated') and r.end_at > pg_catalog.now()
  group by r.id
)
select section, "check", status, detail from (
select 1 as ord, 'ledger' as section, 'production is at S109' as "check",
  case when (select max(version) from supabase_migrations.schema_migrations) = {lit(S109)} then 'PASS' else 'FAIL' end as status,
  'last migration ' || coalesce((select max(version) from supabase_migrations.schema_migrations), 'none') as detail
union all select 2, 'ledger', 'no S110 row yet',
  case when not exists (select 1 from supabase_migrations.schema_migrations where version = {lit(S110)}) then 'PASS' else 'FAIL' end, ''
union all select 3, * from ({' union all '.join('select * from (' + r + ') x' for r in rows)}) d
union all select 4, 'not yet released', 'booking_check_seat_group absent',
  case when not exists (select 1 from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'atlas_private' and p.proname = 'booking_check_seat_group') then 'PASS' else 'FAIL' end, ''
union all select 5, 'settings', 'turnaround / online cap (unchanged by S110)', 'INFO',
  (select 'turnaround ' || turnaround_minutes || ' min, max_party_online ' || max_party_online
     || ', public_online_enabled ' || public_online_enabled from atlas_private.booking_settings where id = true)
union all select 6, 'impact', 'future allocations with fewer seats than guests (could not be re-assigned unchanged)',
  case when exists (select 1 from live where capacity < party_size) then 'WARN' else 'PASS' end,
  coalesce((select string_agg(booking_reference || ' (' || party_size || ' guests, ' || capacity || ' seats)', '; ') from live where capacity < party_size), 'none')
union all select 7, 'impact', 'future multi-seat allocations that are not one adjacent group in one section',
  case when exists (select 1 from live where pg_catalog.cardinality(seats) > 1
                    and not atlas_private.booking_tables_contiguous_segment(seats)) then 'WARN' else 'PASS' end,
  coalesce((select string_agg(booking_reference, '; ') from live where pg_catalog.cardinality(seats) > 1
                    and not atlas_private.booking_tables_contiguous_segment(seats)), 'none')
union all select 8, 'impact', 'future active bookings (all sources)', 'INFO',
  (select pg_catalog.count(*)::text from atlas_private.reservations where start_at > pg_catalog.now()
     and status in ('requested','confirmed','arrived','seated'))
) checks order by ord, "check";
"""
(ROOT / "docs/release/sql/KANEL_S110_preflight_readonly.sql").write_text(sql, encoding="utf-8")
print(f"wrote KANEL_S110_rollback.sql ({len(changed)} restored, {len(added)} dropped), "
      "kanel_pre_s110_expected.json, KANEL_S110_preflight_readonly.sql")
